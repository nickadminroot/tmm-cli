"""JPG 138–143: P4 hot-forging press; Adams ODE and constant-torque energy variant."""
from source_prefaces import preface
from book import Book, cli, Function, S


def build():
    b=Book('04_press','Приложение 4. Проектирование механизма пресса')
    b.page(138,'Общие сведения. П4.1. Синтез. П4.2. Кинематика')
    preface(b,138)
    b.figure('fig_P4_1','Рис. П4.1. Схема пресса и его привода')
    for n,v in [('F_max','35*10**6'),('H',.4),('m_3','50*10**3'),('m_2','30*10**3'),('u_ред',18.6),('I_прI','140*10**3'),('I_2S','5*10**3'),('n_0',16.7),('n_K',12.3),('M_K','5.24*10**3')]: b.D(n,v)
    b.D('g',9.81,why='В блоке исходных данных этого фрагмента g не выписано. Восстановлено по напечатанным весам G₂Y и G₃Y; n₀ и nK заданы в об/с, не об/мин.')
    for n,v in [('l_OA','H/2'),('l_AB','4.7*l_OA'),('l_AS2','2*l_AB/3'),('X_B',0),('φ','rng(0,2*π,deg)'),('ω_q1',-1),('φ_0','π/2'),('f','120*deg')]: b.D(n,v)
    b.E('l_OA','0.200'); b.E('l_AB','0.940'); b.E('l_AS2','0.627')
    b.page(139,'Функции положений, аналоги скоростей и ускорений')
    b.D('φ_1(φ)','φ_0+φ*ω_q1'); b.E('φ_1(f)/deg','−30')
    b.D('X_A(φ)','l_OA*cos(φ_1(φ))'); b.D('Y_A(φ)','l_OA*sin(φ_1(φ))')
    b.D('cs_2(φ)','(X_B-X_A(φ))/l_AB'); b.D('sn_2(φ)','-sqrt(1-cs_2(φ)**2)'); b.D('φ_2(φ)','atan2(cs_2(φ),sn_2(φ))'); b.E('φ_2(f)/deg','−100.618')
    b.D('Y_B(φ)','Y_A(φ)+l_AB*sin(φ_2(φ))')
    b.D('X_S2(φ)','X_A(φ)+l_AS2*cos(φ_2(φ))'); b.D('Y_S2(φ)','Y_A(φ)+l_AS2*sin(φ_2(φ))')
    b.figure('fig_P4_2','Рис. П4.2. Положение и координаты точек механизма пресса')
    b.D('X','[0,X_A(f),X_S2(f),X_B]'); b.D('Y','[0,Y_A(f),Y_S2(f),Y_B(f)]')
    b.plot(('X_A(φ)','Y_A(φ)'),('X_S2(φ)','Y_S2(φ)'),('X_B','Y_B(φ)'),('X','Y'),caption='План механизма и траектории')
    for point,axes in [('S2','XY'),('B','Y')]:
        for ax in axes: b.derivative(f'V_q{point}{ax}',f'{ax}_{point}')
    b.derivative('ω_q2','φ_2')
    b.plot(('φ/deg','V_qS2X(φ)'),('φ/deg','V_qS2Y(φ)'),('φ/deg','V_qBY(φ)'), x_bounds=(0, 360), caption='Аналоги линейных скоростей')
    b.plot(('φ/deg','ω_q2(φ)'), x_bounds=(0, 360), caption='Аналог угловой скорости шатуна')
    for point,axes in [('S2','XY'),('B','Y')]:
        for ax in axes: b.derivative(f'a_q{point}{ax}',f'{ax}_{point}',degree=2)
    b.derivative('ε_q2','φ_2',degree=2)
    b.D('G_2Y','-m_2*g'); b.D('G_3Y','-m_3*g'); b.E('G_2Y','−2.943·10⁵'); b.E('G_3Y','−4.905·10⁵')
    b.D('A_H','H*[0,.6,.62,.75,1]'); b.E('A_H','(0;0.240;0.248;0.300;0.400)',shape=(5,1))
    b.page(140,'П4.3. Внешние силы и характеристика двигателя. Приведение сил')
    b.D('A_F','F_max*[0,0,.1,.2,1]'); b.E('A_F','(0;0;3.5·10⁶;7·10⁶;3.5·10⁷)',shape=(5,1))
    b.D('f_3Y(h)','linterp(A_H,A_F,h)'); b.D('h','rng(0,H,H/400)')
    b.plot(('h','f_3Y(h)'),caption='Рис. П4.3. Диаграмма силы деформирования заготовки')
    b.D('h(φ)','-Y_B(φ)+Y_B(0)'); b.E('h(f)','0.284'); b.plot(('φ/deg','h(φ)'), x_bounds=(0, 360), caption='Ход ползуна')
    b.piece('F_3Y(φ)',[('f_3Y(h(φ))','V_qBY(φ)<=0')])
    b.plot(('φ/deg','F_3Y(φ)'), x_bounds=(0, 360), caption='Сила деформирования за цикл; на обратном ходе — нуль')
    b.D('S(n)','1-n/n_0'); b.D('S_K','1-n_K/n_0')
    b.historical('Mд(n) := 2·MK / (S(n)/SK + SK/S(n))', 'При n=n₀ исходная запись делит на нуль. Ниже используется алгебраически эквивалентная непрерывная форма, дающая физический нулевой момент при нулевом скольжении.')
    b.D('M_д(n)','2*M_K*S(n)*S_K/(S(n)**2+S_K**2)')
    b.D('Δ',1); b.D('n','rng(0,n_0+Δ,n_0/1000)')
    b.plot(('n','M_д(n)'),caption='Статическая механическая характеристика двигателя')
    b.D('M_прG2(φ)','G_2Y*V_qS2Y(φ)'); b.D('M_прG3(φ)','G_3Y*V_qBY(φ)'); b.D('M_прF3(φ)','F_3Y(φ)*V_qBY(φ)')
    b.D('M_прC(φ)','M_прG2(φ)+M_прG3(φ)+M_прF3(φ)')
    b.sample('φ','2*π',10000,[('A_M','M_прC')])
    b.plot(('φ/deg','M_прC(φ)'),('φ/deg','M_прF3(φ)'),('φ/deg','M_прG2(φ)'),('φ/deg','M_прG3(φ)'),
           x_bounds=(0, 360), caption='Приведённые моменты сопротивления')
    b.page(141,'П4.4. Приведённые характеристики. П4.5. Численное интегрирование')
    for n,v in [('ω_K','2*π*n_K/u_ред'),('ω_0','2*π*n_0/u_ред'),('ω_max','2*π*(n_0+Δ)/u_ред'),('n(ω)','u_ред*ω/(2*π)')]: b.D(n,v)
    b.E('ω_K','4.155'); b.E('ω_0','5.641'); b.E('ω_max','5.979')
    b.D('M_прДВ(ω)','u_ред*M_д(n(ω))')
    b.historical('MпрДВ(ω) = uред·Mд(n(ω)) при ω≠ω₀; 10⁻¹⁵ иначе', 'После устранения деления на нуль отдельная искусственная ветвь 10⁻¹⁵ не требуется; при ω₀ возвращается 0.')
    b.D('ω','rng(0,ω_max,ω_0/1000)'); b.plot(('ω','M_прДВ(ω)'),caption='Приведённый момент двигателя')
    b.D('M_прΣ(φ,ω)','M_прC(φ)+M_прДВ(ω)')
    b.D('I_пр2(φ)','I_2S*ω_q2(φ)**2+m_2*(V_qS2X(φ)**2+V_qS2Y(φ)**2)')
    b.D('I_пр3(φ)','m_3*V_qBY(φ)**2'); b.D('I_прII(φ)','I_пр2(φ)+I_пр3(φ)')
    b.sample('φ','2*π',10000,[('A_I','I_прII')]); b.D('I_прΣ(φ)','I_прI+I_прII(φ)'); b.derivative('dI','I_прII')
    b.plot(('φ/deg','I_прII(φ)'),('φ/deg','I_пр2(φ)'),('φ/deg','I_пр3(φ)'), x_bounds=(0, 360), caption='Приведённые моменты инерции')
    b.D('ε(φ,ω)','M_прΣ(φ,ω)/I_прΣ(φ)-ω**2*dI(φ)/(2*I_прΣ(φ))')
    b.D('D(t,Y)','[Y[1],ε(Y[0],Y[1])]')
    for n,v in [('t_0',0),('t_ц',3),('y','[0,ω_0]'),('N',10000)]: b.D(n,v)
    b.E('y','(0;5.641)',shape=(2,1))
    b.external_functions.append(Function(S('Adams'),[S(x) for x in ['y','a','b','N','D']]))
    b.D('R','Adams(y,t_0,t_ц,N,D)')
    b.note('Adams сохранён именно как в книге, не заменён незаметно на Runge–Kutta. В supplied xmcd его нет в статическом реестре; здесь объявлена сигнатура внешнего для валидатора имени. Это не реализация решателя и не подтверждение наличия функции в установленной версии Mathcad.')
    b.D('T','col(R,0)'); b.D('Φ','col(R,1)'); b.D('ω','col(R,2)')
    b.D('c_φ','lspline(T,Φ)'); b.D('φ(t)','interp(c_φ,T,Φ,t)')
    b.D('c_ω','lspline(T,ω)'); b.D('ω(t)','interp(c_ω,T,ω,t)')
    b.D('ε_ОДУ(φ,ω)','ε(φ,ω)',why='Сохранена двухаргументная функция ускорения перед переопределением ε(t); явный псевдоним исключает неоднозначность перегрузки для статического валидатора.')
    b.D('ε(t)','ε_ОДУ(φ(t),ω(t))'); b.D('t',0)
    b.D('t_ц','root(φ(t)-2*π,t,0,t_ц)',why='На скане root(φ(t)−2π,t) с начальным t=0. Добавлена ограниченная область уже рассчитанной траектории [0,3], чтобы поиск не выходил за таблицу.')
    b.E('t_ц','2.958')
    b.page(142,'Графики движения. П4.6. Альтернатива: постоянный момент')
    b.D('t','rng(0,t_ц,t_ц/1000)')
    b.plot(('t','φ(t)/deg'),caption='Положение начального звена во времени')
    b.plot(('t','ω(t)'),caption='Угловая скорость во времени')
    b.plot(('t','ε(t)'),caption='Угловое ускорение во времени')
    for n,v in [('N',10000),('Δt','t_ц/N'),('i','rng(0,N)'),('A_φ[i]','φ(Δt*i)'),('A_ω[i]','ω(Δt*i)'),('A_ε[i]','ε(Δt*i)')]: b.D(n,v)
    b.D('c_ω','lspline(A_φ,A_ω)'); b.D('ω(φ)','interp(c_ω,A_φ,A_ω,φ)')
    b.D('c_ε','lspline(A_φ,A_ε)'); b.D('ε(φ)','interp(c_ε,A_φ,A_ε,φ)')
    b.D('φ','rng(0,2*π,deg)')
    b.plot(('φ/deg','ω(φ)'), x_bounds=(0, 360), caption='Угловая скорость по углу'); b.plot(('φ/deg','ε(φ)'), x_bounds=(0, 360), caption='Угловое ускорение по углу')
    b.D('M_прДВ(φ)','M_прДВ(ω(φ))'); b.plot(('φ/deg','M_прДВ(φ)'), x_bounds=(0, 360), caption='Момент двигателя в течение рабочего цикла')
    b.text('П4.6. Исследование без учёта статической характеристики двигателя',heading=True)
    b.D('M_ДВ','5.24*10**3'); b.D('M_прДВ','M_ДВ*u_ред'); b.E('M_прДВ','9.746·10⁴')
    b.D('M_прΣ(φ)','M_прC(φ)+M_прДВ'); b.D('A_ДВ(φ)','M_прДВ*φ'); b.D('A_C(φ)','intg(M_прC(q),q,0,φ)'); b.D('A_Σ(φ)','A_ДВ(φ)+A_C(φ)'); b.E('A_Σ(2*π)','−1.775·10⁶')
    b.page(143,'Работа сил, скорость, ускорение и время при постоянном моменте')
    b.plot(('φ/deg','A_ДВ(φ)'),('φ/deg','A_C(φ)'),('φ/deg','A_Σ(φ)'), x_bounds=(0, 360), caption='Работы сил при постоянном движущем моменте')
    b.D('ω_нач','2*π*n_0/u_ред'); b.E('ω_нач','5.641')
    b.D('ω(φ)','sqrt((2*(A_Σ(φ)-A_Σ(0))+ω_нач**2*I_прΣ(0))/I_прΣ(φ))'); b.E('ω(2*π)','2.557')
    b.plot(('φ/deg','ω(φ)'), x_bounds=(0, 360), caption='Скорость при постоянном моменте двигателя')
    b.D('ε(φ)','(M_прΣ(φ)-dI(φ)*ω(φ)**2/2)/I_прΣ(φ)'); b.E('ε(f)','−5.960'); b.plot(('φ/deg','ε(φ)'), x_bounds=(0, 360), caption='Ускорение при постоянном моменте двигателя')
    b.D('t(φ)','intg(1/ω(q),q,0,φ)'); b.E('t(2*π)','1.864'); b.plot(('φ/deg','t(φ)'), x_bounds=(0, 360), caption='Время достижения положения')
    b.note('Обе модели — разные допущения, а не два численных метода одной задачи. Проверять положительность кинетической энергии; при остановке нельзя продолжать интегрирование по углу через ω=0. Процесс мгновенного сцепления и восстановление скорости между ходами не рассчитаны в представленном фрагменте.')
    return b

if __name__=='__main__': cli(build)
