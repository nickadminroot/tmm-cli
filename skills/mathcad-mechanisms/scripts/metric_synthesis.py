    b.text('Внеосность:'); b.D('e','l_1*λ_e'); b.E('e','0.045')
    b.D('X_н','[0,l_1*cos(φ_1н),X_Cн]'); b.D('X_к','[0,l_1*cos(φ_1к),X_Cн-h_C]')
    b.D('Y_н','[0,l_1*sin(φ_1н),e]'); b.D('Y_к','[0,l_1*sin(φ_1к),e]')
    b.plot(('X_н','Y_н'),('X_к','Y_к'), caption='Два заданных положения механизма',markers=True)
    b.text('П1.2. Определение длин звеньев четырёхшарнирного механизма по двум его крайним положениям',heading=True)
    b.text('Исходные данные:')
