    b.text('Начальные приближения:')
    for n,v in [('l_1',0.2),('l_2',0.5),('φ_1н','30*deg'),('θ','30*deg')]: b.D(n,v)
    b.given(*fourbar_constraints()); b.solve(['l_1','l_2','φ_1н','θ'])
    b.E('U','(0.242; 0.798; 0.364; 0.170)',shape=(4,1)); b.E('φ_1н/deg','20.851'); b.E('θ/deg','9.747')
    fourbar_vectors(b)

    b.page(114,'Продолжение П1.2. П1.3 и начало П1.4')
    b.plot(('X_н','Y_н'),('X_к','Y_к'),caption='П1.2. Крайние положения',markers=True)
    b.text('П1.3. Определение длин звеньев по двум крайним положениям механизма и коэффициенту изменения средней угловой скорости коромысла',heading=True)
    for n,v in [('Y_D',-0.1),('l_3',0.5),('K_ω',1.2),('γ_н','50*deg'),('γ_к','110*deg')]: b.D(n,v)
