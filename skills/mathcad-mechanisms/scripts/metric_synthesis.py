    b.E('U','(0.495; 0.277; 0.801; 2.329; 2.546; −0.121)',shape=(6,1))
    b.D('θ_н','φ_1+π/2-φ_3н'); b.E('θ_н','0.043'); b.E('θ_н/deg','2.435')
    b.D('A2','[X_D,l_1,φ_1/deg,φ_3н/deg,φ_3к/deg,Y_D,θ_н/deg,θ_к/deg]')
