    b.text('Начальные приближения:')
    for n,v in [('l_1',0.2),('l_2',0.5),('φ_1н','30*deg'),('X_D',0.5)]: b.D(n,v)
    b.given(*fourbar_constraints()); b.solve(['l_1','l_2','φ_1н','X_D'])
    b.historical('Find(l₁,l₂,φ₁н,θ)', 'В П1.3 на скане последний аргумент Find — θ, хотя θ уже задан коэффициентом K_ω, а неизвестная X_D стоит слева. В исполняемом блоке найден X_D. Напечатанный контрольный вектор не удовлетворяет исправленной системе при K_ω=1.2; независимый расчёт даёт l₁≈0.213304, l₂≈0.940712, φ₁н≈14.196609°, X_D≈0.797378. Это не погрешность округления, поэтому не подгонять результат под скан.')
    b.E('[l_1,l_2,φ_1н/deg,X_D]','(0.187; 0.682; 19.012; 0.512)',shape=(4,1))
    fourbar_vectors(b); b.plot(('X_н','Y_н'),('X_к','Y_к'),caption='П1.3. Крайние положения',markers=True)
    b.text('П1.4. Определение длин звеньев по трём положениям механизма',heading=True)
    for n,v in [('X_D',0.5),('Y_D',-0.1),('l_3',0.5),('γ_1','70*deg'),('γ_2','80*deg'),('γ_3','120*deg'),('φ_12','30*deg'),('φ_13','120*deg')]: b.D(n,v)
    b.text('Начальные приближения:')
    for n,v in [('l_1',0.2),('l_2',0.5),('φ_1н','30*deg'),('φ_21','10*deg'),('φ_22','20*deg'),('φ_23','30*deg')]: b.D(n,v)
    constraints=[]
