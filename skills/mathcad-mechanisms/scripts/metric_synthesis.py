    for n,v in [('h_min',0.05),('h_max',0.3),('β','60*deg'),('θ_к','50*deg'),('Y_D',0.05),('l_шт','1.3*h_max')]: b.D(n,v)
    b.E('l_шт','0.39')
    for n,v in [('X_D','2*h_max'),('l_1','h_max'),('φ_1','90*deg'),('φ_3н','120*deg'),('φ_3к','150*deg')]: b.D(n,v)
    b.given(*cylinder_constraints()); b.solve(['X_D','l_1','φ_1','φ_3н','φ_3к'])
