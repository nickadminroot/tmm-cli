    b.page(113, 'П1.1. Проектирование кривошипно-ползунного механизма по двум заданным положениям кривошипа и ходу ползуна')
    b.text('Исходные данные:')
    for n,v in [('λ_2',2.5),('λ_e',0.4),('φ_1н','60*deg'),('φ_1к','150*deg'),('h_C',0.15)]: b.D(n,v)
    b.text('Начальные приближения:')
    for n,v in [('l_1',0.2),('φ_2н',0),('φ_2к',0),('X_Cн',0.7)]: b.D(n,v)
