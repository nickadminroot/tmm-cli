    b.page(116,'П1.5, варианты 2 и 3')
    b.plot(('X_н','Y_н'),('X_к','Y_к'),caption='Вариант 1',markers=True)
    b.text('Вариант 2. Пять уравнений, шесть неизвестных; регламентируется угол давления в конечном положении.')
    for n,v in [('h_min',0.05),('h_max',0.3),('β','60*deg'),('θ_к','50*deg'),('l_шт','1.3*h_max'),('X_D','2*h_max'),('l_1','h_max'),('φ_1','90*deg'),('φ_3н','120*deg'),('φ_3к','150*deg'),('Y_D',0)]: b.D(n,v)
