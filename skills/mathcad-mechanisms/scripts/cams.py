"""JPG 150–155: P6.1–P6.5.3, cam synthesis; end exactly at the fragment boundary."""
from book import Book, cli


def acceleration(b, normalized=False):
    scale='/μ_у' if normalized else ''
    b.piece('a_qу(φ)',[(f'(π/f_1*sin(π*φ/f_1)){scale}','0<=φ and φ<f_1'),
                       (f'(-π/(f_2-f_1)*sin(π*(f_2-φ)/(f_2-f_1))){scale}','f_1<=φ and φ<=f_2'),
                       ('0','f_2<φ and φ<=f_3')])
    b.piece('a_qс(φ)',[('-a_3*Φ(φ-f_3)+(a_3+a_4)*Φ(φ-f_4)-a_4*Φ(φ-f_5)','f_3<φ and φ<=f_5')])
    b.piece('a_q(φ)',[('a_qу(φ)','0<=φ and φ<=f_3')],default='a_qс(φ)')
    b.D('v_q(φ)','intg(a_q(q),q,0,φ)')


def rays(b, center='s_0', ycenter=False):
    sign='-' if ycenter else '+'
    b.D('x_л(y)',f'e-tan(θ_л)*(y{sign}{center})')
    b.D('x_п(y)',f'e+tan(θ_п)*(y{sign}{center})')


def portrait(b, caption, lines=True, pl='φ_л',pr='φ_п'):
    pairs=[('v_q(φ)','S(φ)'),(f'v_q({pl})',f'S({pl})'),(f'v_q({pr})',f'S({pr})')]
    if lines: pairs += [('x_л(y)','y'),('x_п(y)','y')]
    pairs += [('X_тр','Y_тр')]
    b.plot(*pairs,caption=caption)


def build():
    b=Book('06_cams','Приложение 6. Синтез кулачковых механизмов')
    b.page(150,'Исходные данные. П6.1. Фазовые углы. П6.2. Кинематические диаграммы')
    b.text('Угол рабочего профиля ψ_p, углы удаления ψ_у и сближения ψ_с, угол дальнего стояния ψ_д. Коэффициенты пропорциональности ускорений ν_у, ν_с соответствуют рис. 7.4; относительные фазовые углы k_i — табл. 7.1 (рисунок и таблица находятся вне предоставленного диапазона). Знак ω_q1 определяет направление вращения.')
    for n,v in [('ψ_p','330*deg'),('ψ_у','120*deg'),('ψ_с','180*deg'),('ψ_д','ψ_p-ψ_у-ψ_с'),('ν_у',3),('ν_с',2.5),('a_1',1),('a_3',1),('a_2','a_1*ν_у'),('a_4','a_3*ν_с'),('h',.08),('θ_у','30*deg'),('θ_с','50*deg'),('δ_у','π/2-θ_у'),('δ_с','π/2-θ_с'),('ω_q1',-1)]: b.D(n,v)
    for n,v in [('ψ_д/deg','30'),('a_2','3'),('a_4','2.5'),('δ_у','1.047'),('δ_с','0.698')]: b.E(n,v)
    for n,v in [('f_0',0),('f_1','f_0+a_2*ψ_у/(a_1+a_2)'),('f_2','ψ_у'),('f_3','ψ_у+ψ_д'),('f_4','f_3+a_4*ψ_с/(a_3+a_4)'),('f_5','ψ_p')]: b.D(n,v)
    for j,v in [(1,'90'),(2,'120'),(3,'150'),(4,'278.571'),(5,'330')]: b.E(f'f_{j}/deg',v)
    b.piece('Φ(x)',[('0','x<=0')],default='1')
    acceleration(b); b.D('φ','rng(0,2*π,.001)')
    b.plot(('φ/deg','a_q(φ)'), x_bounds=(0, 360), caption='Ненормированный аналог ускорения: синусоидальное удаление и ступенчатое сближение')
    b.D('S(φ)','intg(v_q(q),q,0,φ)')
    b.page(151,'П6.3. Нормирование закона движения. П6.4. Поступательный толкатель')
    b.D('H_у','S(f_2)'); b.E('H_у','2.094'); b.D('μ_у','H_у/h'); b.E('μ_у','26.18')
    b.D('H_с','S(f_3)-S(f_5)'); b.E('H_с','3.525')
    b.D('a_3','a_3*h/abs(H_с)'); b.D('a_4','a_4*a_3')
    b.note('Последнее переопределение a₄:=a₄·a₃ соответствует исходному a₃=1. Для произвольной исходной нормировки явно восстановить отношение a₄/a₃=ν_с, а не умножать повторно уже нормированные значения.')
    acceleration(b,normalized=True)
    b.D('N',240); b.D('Δφ','2*π/N'); b.D('i','rng(0,N)'); b.D('A_φ[i]','Δφ*i'); b.D('A_vq[i]','v_q(A_φ[i])')
    b.D('v_q(φ)','linterp(A_φ,A_vq,φ)'); b.D('S(φ)','intg(v_q(q),q,0,φ)')
    b.E('S(f_2)','0.080'); b.E('S(f_3)','0.080')
    b.plot(('φ/deg','a_q(φ)'), x_bounds=(0, 360), caption='Нормированный аналог ускорения')
    b.plot(('φ/deg','v_q(φ)'), x_bounds=(0, 360), caption='Нормированный аналог скорости')
    b.plot(('φ/deg','S(φ)'), x_bounds=(0, 360), caption='Перемещение толкателя')
    b.text('П6.4. Метрический синтез и профилирование механизма с поступательным толкателем',heading=True)
    b.D('ω_q1',-1); b.text('Максимумы модуля скорости соответствуют фазовым углам f₁ и f₄. Строится фазовый портрет (v_q,S) с учётом направления вращения.')
    b.D('v_кин(φ)','v_q(φ)',why='Служебное сохранение кинематического аналога перед изменением ориентации фазового портрета.')
    b.D('v_q(φ)','-v_кин(φ)*ω_q1')
    b.D('X_тр','[0,0]'); b.D('Y_тр','[0,h]')
    b.piece('f_л',[('f_1','ω_q1==1')],default='f_4'); b.piece('f_п',[('f_4','ω_q1==1')],default='f_1')
    b.page(152,'П6.4.1. Фазовый портрет. Приближённое и точное определение параметров')
    for a,va,vb in [('θ_л','θ_у','θ_с'),('θ_п','θ_с','θ_у'),('δ_л','δ_у','δ_с'),('δ_п','δ_с','δ_у')]: b.piece(a,[(va,'ω_q1==1')],default=vb)
    portrait(b,'Фазовый портрет и положения максимальных скоростей',False,pl='f_л',pr='f_п')
    b.text('П6.4.2. Приближённое определение основных параметров',heading=True)
    b.D('s_0','h'); b.D('e',0)
    b.given('tan(θ_п)==(v_q(f_п)-e)/(s_0+S(f_п))',
            'tan(θ_л)==(-v_q(f_л)+e)/(s_0+S(f_л))')
    b.D('U','Find(s_0,e)'); b.D('s_0пр','U[0]'); b.D('e_пр','U[1]'); b.E('s_0пр','0.037'); b.E('e_пр','0.021')
    b.D('r_0пр','sqrt(s_0пр**2+e_пр**2)'); b.E('r_0пр','0.042')
    b.D('x_л(y)','e_пр-tan(θ_л)*(y+s_0пр)'); b.D('x_п(y)','e_пр+tan(θ_п)*(y+s_0пр)')
    b.D('y','rng(-s_0пр,h,-s_0пр+.001)',why='Шаг построения лучей принят 0.001 м. Напечатанное «−s₀пр,0.001..h» в Mathcad задаёт второе значение, а не величину шага; геометрия прямых от этого не зависит.')
    portrait(b,'Приближённое положение центра кулачка',pl='f_л',pr='f_п')
    b.text('П6.4.3. Уточнение по касанию лучей к фазовому портрету',heading=True)
    b.D('K_п(φ)','v_q(φ)/a_q(φ)-tan(δ_п)'); b.D('φ_п','f_п-Δφ/6'); b.E('φ_п/deg','89.75')
    b.given('K_п(φ_п)==10**-5'); b.D('φ_п','Minerr(φ_п)'); b.E('φ_п/deg','73.900')
    b.D('K_л(φ)','v_q(φ)/a_q(φ)-tan(π-δ_л)'); b.D('φ_л','f_л-Δφ/6'); b.E('φ_л/deg','278.321')
    b.given('K_л(φ_л)==10**-5'); b.D('φ_л','Minerr(φ_л)'); b.E('φ_л/deg','281.924')
    b.note('Отношение v_q/a_q не определено при a_q=0. Minerr и начальные приближения относятся к заданным фазам; при другом законе проверять фазу, остаток и действительное касание, а не только статус решателя.')
    b.page(153,'Два способа нахождения центра. П6.4.4. Угол давления')
    b.text('Способ 1. Пересечение касательных в координатах фазового портрета',heading=True)
    b.D('Y','h'); b.D('X',0)
    b.given('Y-S(φ_п)-tan(δ_п)*(X-v_q(φ_п))==10**-7',
            'Y-S(φ_л)-tan(π-δ_л)*(X-v_q(φ_л))==10**-7')
    b.D('U','Find(Y,X)'); b.D('s_0','U[0]'); b.D('e','U[1]'); b.D('r_0','sqrt(s_0**2+e**2)')
    b.E('s_0','−0.041'); b.E('e','0.025'); b.E('r_0','0.047')
    rays(b,ycenter=True); b.D('y','rng(s_0,h,s_0+.001)'); portrait(b,'Способ 1: s₀ — отрицательная ордината центра')
    b.text('Способ 2. Непосредственное использование ограничений угла давления',heading=True)
    b.D('s_0',.02); b.D('e',0)
    b.given('tan(θ_п)==(v_q(φ_п)-e)/(s_0+S(φ_п))',
            'tan(θ_л)==(-v_q(φ_л)+e)/(s_0+S(φ_л))')
    b.solve(['s_0','e']); b.D('r_0','sqrt(s_0**2+e**2)'); b.E('s_0','0.041'); b.E('e','0.025'); b.E('r_0','0.047')
    rays(b); b.D('y','rng(-s_0,h,-s_0+.001)'); portrait(b,'Способ 2: s₀ — положительное начальное удаление')
    b.note('В способах 1 и 2 символ s₀ имеет противоположный знак: ордината центра и положительное начальное удаление. Не смешивать две конвенции в формуле угла давления или профиля.')
    b.reference('Приближённый расчёт r₀пр=0.042, eпр=0.021; уточнённый r₀=0.047, e=0.025.')
    b.D('Δ_r','(r_0-r_0пр)/r_0'); b.D('Δ_e','(e-e_пр)/e'); b.E('100*Δ_r','11.172 %'); b.E('100*Δ_e','16.277 %')
    b.D('tgθ(φ)','(v_q(φ)-e)/(s_0+S(φ))'); b.D('θ(φ)','atan(tgθ(φ))')
    b.plot(('φ/deg','θ(φ)/deg'),('φ/deg','θ_у/deg'),('φ/deg','-θ_с/deg'), x_bounds=(0, 360), caption='П6.4.4. Угол давления и допустимые пределы')
    b.page(154,'П6.4.5. Профилирование. П6.5. Коромысловый толкатель')
    for n,v in [('x_A(φ)','-e*cos(φ)'),('y_A(φ)','-e*sin(φ)'),('x_B(φ)','x_A(φ)-s_0*sin(φ)'),('y_B(φ)','y_A(φ)+s_0*cos(φ)'),('x_C(φ)','e*cos(φ)-ω_q1*(s_0+S(φ))*sin(φ)'),('y_C(φ)','ω_q1*e*sin(φ)+(s_0+S(φ))*cos(φ)')]: b.D(n,v)
    b.plot(('-x_C(φ)','y_C(φ)'),('x_B(φ)','y_B(φ)'),caption='Центровой профиль кулачка и основная окружность')
    b.D('r_рол',.02)
    b.D('x_K(φ)','-ω_q1*(ω_q1*x_C(φ)-r_рол*cos((φ+π/2)+ω_q1*θ(φ)))')
    b.D('y_K(φ)','y_C(φ)-r_рол*sin((φ+π/2)+ω_q1*θ(φ))')
    b.D('f',0); b.D('x_p(φ)','-x_C(f)+r_рол*cos(φ)'); b.D('y_p(φ)','y_C(f)+r_рол*sin(φ)')
    b.D('X','[-x_C(f),-x_C(f)-h*sin(f)]'); b.D('Y','[y_C(f),y_C(f)+h*cos(f)]')
    b.plot(('x_A(φ)','y_A(φ)'),('x_B(φ)','y_B(φ)'),('-x_C(φ)','y_C(φ)'),('x_K(φ)','y_K(φ)'),('x_p(φ)','y_p(φ)'),('X','Y'),('0','0'),caption='Конструктивный профиль, центровой профиль, ролик и толкатель')
    b.text('В книге приведена ссылка на приложение 7, лист L4.1_П6. Это приложение не входит в предоставленные сканы.')
    b.note('r_рол=0.02 сохранено из этого примера. Оно не удовлетворяет рекомендуемой пропорции (0.25…0.40)r₀ из JPG 112 при r₀≈0.047; это разные учебные фрагменты. Для нового варианта отдельно проверить кривизну, подрезание и контакт; не считать такое число универсально допустимым.')
    b.text('П6.5. Метрический синтез механизма с коромысловым толкателем',heading=True)
    b.D('ω_q1',1); b.D('l_T',.15); b.D('φ_2(φ)','S(φ)/l_T'); b.D('ρ(φ)','l_T-v_q(φ)*ω_q1')
    b.D('X_B(φ)','l_T*cos(φ_2(φ))'); b.D('Y_B(φ)','l_T*sin(φ_2(φ))')
    b.D('N_x(φ)','ρ(φ)*cos(φ_2(φ))'); b.D('N_y(φ)','ρ(φ)*sin(φ_2(φ))')
    b.D('Y_r(X_x,Fi)','tan(φ_2(Fi))*(X_x-N_x(Fi))+N_y(Fi)')
    b.text('П6.5.1. Метод линий уровня',heading=True)
    b.piece('k_Vi(φ)',[('tan(φ_2(φ)+π/2+θ_у*ω_q1)','f_0<=φ and φ<=f_2'),
                       ('tan(φ_2(φ)+π/2-θ_с*ω_q1)','f_3<=φ and φ<=f_5')])
    b.page(155,'Метод линий уровня. П6.5.2. Построение. П6.5.3. Угол давления')
    b.text('Положения максимальных скоростей: удаление f₁, сближение f₄.')
    b.piece('f_п',[('f_4','ω_q1==1')],default='f_1'); b.piece('f_л',[('f_1','ω_q1==1')],default='f_4')
    b.D('b_Vi(φ)','N_y(φ)-k_Vi(φ)*N_x(φ)')
    b.D('X_1','-(b_Vi(f_л)-b_Vi(f_п))/(k_Vi(f_л)-k_Vi(f_п))')
    b.D('Y_1','(k_Vi(f_п)*b_Vi(f_л)-k_Vi(f_л)*b_Vi(f_п))/(k_Vi(f_п)-k_Vi(f_л))')
    b.E('X_1','0.145'); b.E('Y_1','−0.030')
    b.D('X_Vi(φ)','(Y_1-b_Vi(φ))/k_Vi(φ)-X_1')
    b.D('φ_у','rng(f_0,f_2,f_0+.001)'); b.D('φ_с','rng(f_3,f_5,f_3+.001)')
    b.plot(('φ_у/deg','X_Vi(φ_у)'),('φ_с/deg','X_Vi(φ_с)'), x_bounds=(0, 360), caption='Функция линий уровня только на рабочих фазах')
    b.note('На стояниях k_Vi=0 и X_Vi не определена. График не соединяется через деление на нуль; введены отдельные диапазоны удаления и сближения.')
    b.D('Φ_Vmin','50*deg'); b.given('X_Vi(Φ_Vmin)==-.1','60*deg<Φ_Vmin','Φ_Vmin<130*deg'); b.D('φ_Vmin','Minerr(Φ_Vmin)'); b.E('φ_Vmin/deg','67.5')
    b.D('Φ_Vmax','245*deg'); b.given('X_Vi(Φ_Vmax)==.1','220*deg<Φ_Vmax','Φ_Vmax<320*deg'); b.D('φ_Vmax','Minerr(Φ_Vmax)'); b.E('φ_Vmax/deg','279')
    b.note('Minerr с целевыми −0.1 и +0.1 — приём поиска крайних отклонений через недостижимую целевую ординату, а не доказательство равенства X_Vi=±0.1. Для нового варианта явно проверить экстремумы на допустимых фазах и касание. Верхняя граница 130° в исходнике заходит на стояние; решение должно остаться на рабочем участке до 120°.')
    b.D('X_2','-(b_Vi(φ_Vmax)-b_Vi(φ_Vmin))/(k_Vi(φ_Vmax)-k_Vi(φ_Vmin))')
    b.D('Y_2','(k_Vi(φ_Vmax)*b_Vi(φ_Vmin)-k_Vi(φ_Vmin)*b_Vi(φ_Vmax))/(k_Vi(φ_Vmax)-k_Vi(φ_Vmin))')
    b.E('X_2','0.136'); b.E('Y_2','−0.041')
    b.D('j','rng(0,2)')
    for name,angles,X,Y in [('1',['f_п','f_л'],'X_1','Y_1'),('2',['φ_Vmin','φ_Vmax'],'X_2','Y_2')]:
        for j,q in [(0,angles[0]),(2,angles[1])]: b.D(f'x{name}[{j}]',f'N_x({q})'); b.D(f'y{name}[{j}]',f'N_y({q})')
        b.D(f'x{name}[1]',X); b.D(f'y{name}[1]',Y)
    b.D('X_x','rng(0,.25,.001)',why='Диапазон абсцисс для вспомогательных лучей восстановлен по графику; на решение X₂,Y₂ не влияет.')
    b.plot(('N_x(φ)','N_y(φ)'),('X_B(φ)','Y_B(φ)'),('X_x','Y_r(X_x,f_1)'),('X_x','Y_r(X_x,f_4)'),('x1','y1'),('x2','y2'),('0','0'),caption='П6.5.2. Графическое представление метода линий уровня')
    b.D('a_w','sqrt(X_2**2+Y_2**2)'); b.E('a_w','0.142'); b.D('φ_20','atan(abs(Y_2/X_2))'); b.E('φ_20/deg','16.776')
    b.text('П6.5.3. Угол давления',heading=True)
    b.D('θ(φ)','atan((v_q(φ)*ω_q1+a_w*cos(φ_20+φ_2(φ))-l_T)/(a_w*sin(φ_20+φ_2(φ))))')
    b.note('При N=240 интерполяция v_q даёт небольшой остаток S(2π)≈5.56·10⁻⁶ м в независимом расчёте. В произвольном варианте проверять замыкание закона и чувствительность к сетке, не сшивать профиль сглаживанием без проверки движения.')
    b.note('Здесь заканчивается JPG 155, печатная страница 154. Последующий график, центровой и конструктивный профили коромыслового механизма, проверка кривизны и другие продолжения отсутствуют. Агент должен написать недостающие части для своего варианта сам, сохраняя стиль; не выдавать придуманный текст за продолжение скана.')
    return b

